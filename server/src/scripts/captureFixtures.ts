/**
 * pnpm capture-fixtures: regenerate test/fixtures.ts from the doc in DOC_SLUG (read-only).
 * Refuses unless the doc is owned by the signed-in account, so fixtures only ever come from our own test doc.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { config } from "../config.js";
import { DocsPlus, flattenOutline, parseFrame } from "../docsPlus.js";
import { connect, defaultStore, makeProvider } from "../mcp.js";

async function main() {
  const { client } = await connect(makeProvider(defaultStore()));
  const call = async (name: string, args: Record<string, unknown>) => {
    const res = await client.callTool({ name, arguments: args });
    const text = (res.content as Array<{ type: string; text?: string }>).filter((c) => c.type === "text").map((c) => c.text).join("\n");
    if (res.isError) throw new Error(`${name}: ${text}`);
    return text;
  };

  const outlineText = await call("get_outline", { slug: config.docSlug });
  if (!parseFrame(outlineText).ownedByYou) {
    throw new Error(`${config.docSlug} is not owned by you. Run \`pnpm create-test-doc\` and capture from the test doc.`);
  }
  const outline = await new DocsPlus(client, config.docSlug).getOutline();

  const sections: Record<string, string> = {};
  for (const node of flattenOutline(outline.nodes)) {
    if (!node.sectionId) continue;
    sections[node.title] = await call("read_document", { slug: config.docSlug, section_id: node.sectionId });
  }

  const out = `// GENERATED by \`pnpm capture-fixtures\` on ${new Date().toISOString().slice(0, 10)} from our own TEST doc
// (${config.docSlug}, fictional data defined in src/seed/testRecipes.ts). Raw docs.plus responses. Do not edit by hand.

export const OUTLINE = ${JSON.stringify(outlineText)};

/** read_document(section_id) responses, keyed by outline title. */
export const SECTIONS: Record<string, string> = ${JSON.stringify(sections, null, 2)};
`;
  const file = path.join(config.repoRoot, "server/test/fixtures.ts");
  await writeFile(file, out);
  console.log(`Wrote ${Object.keys(sections).length} sections + outline to ${path.relative(config.repoRoot, file)}`);
  await client.close();
}

main().then(
  () => process.exit(0),
  (err) => {
    console.error(`capture-fixtures failed: ${err instanceof Error ? err.message : err}`);
    process.exit(1);
  },
);
